using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Nullean.Argh;

public sealed partial class CliParserGenerator
{
	/// <summary>
	/// Compiler-recognised attributes that the generated code uses and that older targets (netstandard2.0, .NET Framework)
	/// don't define. A flags value so the polyfill step's output compares by value and stays cached across edits.
	/// </summary>
	[Flags]
	internal enum PolyfillNeeds
	{
		None = 0,
		ModuleInitializer = 1,
		NotNullWhen = 2,
	}

	private const string ModuleInitializerAttributeMetadataName = "System.Runtime.CompilerServices.ModuleInitializerAttribute";
	private const string NotNullWhenAttributeMetadataName = "System.Diagnostics.CodeAnalysis.NotNullWhenAttribute";

	/// <summary>
	/// Runs once per compilation, so it does only a few metadata-name lookups. The compilation it sees never contains
	/// this generator's own output, so an emitted polyfill can't switch the answer off again.
	/// </summary>
	private static PolyfillNeeds DetectPolyfillNeeds(Compilation compilation)
	{
		var needs = PolyfillNeeds.None;
		if (!HasAccessibleType(compilation, ModuleInitializerAttributeMetadataName))
			needs |= PolyfillNeeds.ModuleInitializer;
		if (!HasAccessibleType(compilation, NotNullWhenAttributeMetadataName))
			needs |= PolyfillNeeds.NotNullWhen;
		return needs;
	}

	/// <summary>
	/// Whether the compilation can use a type with this metadata name: its own definition, a public one in a reference,
	/// or an internal one it has <c>InternalsVisibleTo</c> access to. Like the <c>GetBestTypeByMetadataName</c> helper that
	/// System.Text.Json's generator uses, it checks every candidate, because <c>GetTypeByMetadataName</c> returns null
	/// when more than one assembly defines the type.
	/// </summary>
	private static bool HasAccessibleType(Compilation compilation, string metadataName)
	{
		foreach (var type in compilation.GetTypesByMetadataName(metadataName))
		{
			if (compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
				return true;
		}

		return false;
	}

	/// <summary>Emits an internal definition of each attribute in <paramref name="needs"/>.</summary>
	private static void EmitPolyfills(SourceProductionContext context, PolyfillNeeds needs)
	{
		if (needs == PolyfillNeeds.None)
			return;

		var w = new CodeWriter();
		w.Line("// <auto-generated/>");
		w.Line("// Attributes the Argh-generated code uses that this target framework doesn't define. Each one is emitted");
		w.Line("// only when the compilation has no accessible definition of its own.");
		w.Line("#nullable enable");
		if ((needs & PolyfillNeeds.ModuleInitializer) != 0)
		{
			w.Line();
			using (w.Block("namespace System.Runtime.CompilerServices"))
			{
				w.Line("[global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]");
				w.Line("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
				using (w.Block("internal sealed class ModuleInitializerAttribute : global::System.Attribute")) { }
			}
		}

		if ((needs & PolyfillNeeds.NotNullWhen) != 0)
		{
			w.Line();
			using (w.Block("namespace System.Diagnostics.CodeAnalysis"))
			{
				w.Line("[global::System.AttributeUsage(global::System.AttributeTargets.Parameter, Inherited = false)]");
				w.Line("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
				using (w.Block("internal sealed class NotNullWhenAttribute : global::System.Attribute"))
				{
					w.Line("public NotNullWhenAttribute(bool returnValue) => ReturnValue = returnValue;");
					w.Line();
					w.Line("public bool ReturnValue { get; }");
				}
			}
		}

		AddSource(context, "ArghPolyfills.g.cs", w);
	}

	private static void AddSource(SourceProductionContext context, string hintName, CodeWriter w) =>
		context.AddSource(hintName, SourceText.From(w.ToString(), Encoding.UTF8));
}
