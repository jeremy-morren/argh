	private const int FuzzyMaxDistance = 2;

	private static void EmitRootCompletionScriptBlock(CodeWriter w, string entryAssemblyName)
	{
		using (w.If("CompletionProtocol.IsCompletionScriptInvocation(args)"))
		{
			using (w.If("!CompletionProtocol.TryParseCompletionScriptInvocation(args, out var __scriptShell)"))
			{
				w.Line("Console.Error.WriteLine(\"Error: expected '__completion bash|zsh|fish|powershell'\");");
				w.Return("2");
			}

			w.Line($"var __entry = {Quote(entryAssemblyName)};");
			using (w.Switch("__scriptShell"))
			{
				foreach (var shell in new[] { "Bash", "Zsh", "Fish", "PowerShell" })
				{
					using (w.Case("CompletionShell." + shell))
					{
						w.Line($"Console.Out.Write(CompletionScriptTemplates.Get{shell}().Replace(\"{{0}}\", __entry));");
						w.Return("0");
					}
				}

				w.Case("default", "return 2;");
			}
		}

		w.Line();
	}


	private static void EmitFuzzyDispatchDefault(
		CodeWriter w,
		RegistryNode node,
		ImmutableArray<string> path,
		string entryAssemblyName)
	{
		var entries = new List<(string Name, string Summary, string HelpPrinter)>();
		foreach (var cmd in node.Commands)
			entries.Add((cmd.CommandName, cmd.SummaryOneLiner, $"PrintHelp_{cmd.RunMethodName}"));
		foreach (var ch in node.Children)
		{
			var childPath = AppendSegment(path, ch.Segment);
			var gk = CommandNamespacePathKey(childPath);
			entries.Add((ch.Segment, "", $"PrintHelp_CommandNamespace_{gk}"));
		}

		var sorted =
			entries.OrderBy(e => e.Name, StringComparer.Ordinal).ToList();

		var pathPrefix = path.IsDefaultOrEmpty ? "" : string.Join(" ", path) + " ";
		var nsHelp = path.IsDefaultOrEmpty ? "--help" : Escape(string.Join(" ", path)) + " --help";
		var nsUsage = $"Console.Error.WriteLine($\"Run '{{__app}} {nsHelp}' for usage.\");";

		w.Line("var __tok = tok;");
		w.Line($"var __app = {Quote(entryAssemblyName)};");
		w.Line($"var __cands = {InlineStringArray(sorted.Select(e => e.Name))};");
		w.Line($"var __matches = FuzzyMatch.FindClosest(__tok, __cands, {FuzzyMaxDistance});");
		const string kind = "command or namespace";
		using (w.If("__matches.Count == 0"))
		{
			w.Line($"Console.Error.WriteLine($\"Error: unknown {kind} '{{__tok}}'.\");");
			w.Line("Console.Error.WriteLine();");
			w.Line(nsUsage);
		}

		using (w.ElseIf("__matches.Count == 1"))
		{
			w.Line("var __m = __matches[0];");
			w.Line($"Console.Error.WriteLine($\"Error: unknown {kind} '{{__tok}}'. Did you mean '{Escape(pathPrefix)}{{__m}}'?\");");
			w.Line("Console.Error.WriteLine();");
			w.Line($"Console.Error.WriteLine($\"Run '{{__app}} {Escape(pathPrefix)}{{__m}} --help' for usage.\");");
			w.Line(nsUsage);
		}

		using (w.Else())
		{
			w.Line($"Console.Error.WriteLine($\"Error: unknown {kind} '{{__tok}}'. Did you mean one of these?\");");
			w.Line("Console.Error.WriteLine();");
			foreach (var e in sorted)
			{
				using (w.If($"__matches.Any(__x => string.Equals(__x, {Quote(e.Name)}, StringComparison.OrdinalIgnoreCase))"))
					w.Line($"Console.Error.WriteLine(\"  \" + CliHelpFormatting.Accent({Quote(pathPrefix + e.Name)}) + \"    {Escape(e.Summary)}\");");
			}

			w.Line("Console.Error.WriteLine();");
			w.Line($"Console.Error.WriteLine($\"Run '{{__app}} {Escape(pathPrefix)}<command> --help' for usage.\");");
			w.Line(nsUsage);
		}

		w.Return("2");
	}


	private static void AppendRunWithCancellationAsyncMethod(CodeWriter w)
	{
		using (w.Block("private static async Task<int> RunWithCancellationAsync(string[] args)"))
		{
			w.Line("using var cts = new CancellationTokenSource();");
			w.Line("Console.CancelKeyPress += (_, e) => { e.Cancel = true; cts.Cancel(); };");
			w.Line("CancellationTokenSource? __linkedCts = null;");
			using (w.Try())
			{
				w.Line("CancellationToken ct = cts.Token;");
				using (w.If("ArghHostRuntime.ApplicationStopping is CancellationToken __hostStopping"))
				{
					w.Line("__linkedCts = CancellationTokenSource.CreateLinkedTokenSource(cts.Token, __hostStopping);");
					w.Line("ct = __linkedCts.Token;");
				}

				w.Return("await RunCoreAsync(args, ct).ConfigureAwait(false)");
			}

			using (w.Catch("Exception ex"))
			{
				w.Line("Console.Error.WriteLine(ex.ToString());");
				w.Return("1");
			}

			using (w.Finally())
				w.Line("__linkedCts?.Dispose();");
		}

		w.Line();
	}

	/// <summary>
	/// Returns <see langword="true"/> if the method or its containing type carries
	/// <c>[NoOptionsInjection]</c>, suppressing AGH0021 and handler-level options-parameter requirements.
	/// Globals/namespaced flags still splice as <see cref="ParameterKind.OptionsInjected"/> for parsing/reconstruction.
	/// </summary>
	private static bool HasNoOptionsInjection(IMethodSymbol method)
	{
		const string attrName = "NoOptionsInjectionAttribute";
		const string ns = "Nullean.Argh";
		foreach (var a in method.GetAttributes())
			if (a.AttributeClass?.Name == attrName && a.AttributeClass.ContainingNamespace?.ToDisplayString() == ns)
				return true;
		foreach (var a in method.ContainingType.GetAttributes())
			if (a.AttributeClass?.Name == attrName && a.AttributeClass.ContainingNamespace?.ToDisplayString() == ns)
				return true;
		return false;
	}

	private static bool HasPublicParameterlessCtor(INamedTypeSymbol type)
	{
		foreach (var ctor in type.InstanceConstructors)
		{
			if (ctor.Parameters.Length == 0 && ctor.DeclaredAccessibility == Accessibility.Public)
				return true;
		}

		return false;
	}

	private static string DiResolveOrNew(string fullyQualifiedType, bool allowParameterlessFallback)
	{
		if (allowParameterlessFallback)
			return $"((ArghServices.ServiceProvider?.GetService(typeof({fullyQualifiedType})) as {fullyQualifiedType}) ?? new {fullyQualifiedType}())";

		return
			$"((ArghServices.ServiceProvider?.GetService(typeof({fullyQualifiedType})) as {fullyQualifiedType}) ?? throw new global::System.InvalidOperationException(\"Register the type in DI for hosted execution, or add a public parameterless constructor for standalone CLI.\"))";
	}

	private static void EmitApp(
		SourceProductionContext context,
		AppEmitModel app,
		CSharpParseOptions parseOptions,
		string entryAssemblyName,
		string entryAssemblyVersion,
		string entrySchemaVersion,
		ReferenceMetadataCapabilities.Capabilities referenceCapabilities)
	{
		_ = referenceCapabilities;
		_ = parseOptions;  // no longer needed for DTO building; kept in signature for future use
		var dtoTargets = CollectDtoBindingTargets(app);
		var root = GetArghGeneratedRootTypeName(entryAssemblyName);
		EmitHierarchical(context, app, dtoTargets, entryAssemblyName, entryAssemblyVersion, entrySchemaVersion, root);
		EmitDtoTypeExtensions(context, dtoTargets, root, app.GeneratedCodeSuppressionPragma);
	}

	private static void EmitHierarchical(
		SourceProductionContext context,
		AppEmitModel app,
		ImmutableArray<DtoBindingTarget> dtoTargets,
		string entryAssemblyName,
		string entryAssemblyVersion,
		string entrySchemaVersion,
		string arghGeneratedRootTypeName)
	{
		var w = new CodeWriter();
		w.Line("// <auto-generated/>");
		w.Line("#nullable enable");
		w.Line(app.GeneratedCodeSuppressionPragma);
		w.Lines(new[]
		{
			"System", "System.Collections.Generic", "System.Globalization", "System.IO", "System.Linq", "System.Threading",
			"System.Threading.Tasks", "Nullean.Argh.Middleware", "Nullean.Argh.Help", "Nullean.Argh.Matching",
			"Nullean.Argh.Runtime", "Nullean.Argh.Schema",
		}.Select(static ns => $"using {ns};"));
		w.Line();
		using (w.Block("namespace Nullean.Argh"))
		{
			w.Line("/// <summary>Source-generated CLI entry point from <c>ArghApp</c> registrations. At the root, <c>__completion bash|zsh|fish|powershell</c> prints a shell script from <see cref=\"global::Nullean.Argh.Help.CompletionScriptTemplates\"/>; each <c>{0}</c> in the template is replaced with the entry assembly name (same effect as <c>string.Format</c>, but substitution uses <c>Replace</c> so shell scripts can contain literal braces).</summary>");
			using (w.Block("public static class " + arghGeneratedRootTypeName))
				EmitArghGeneratedMembers(w, app, dtoTargets, entryAssemblyName, entryAssemblyVersion, entrySchemaVersion);
			AppendArghRuntimeModuleInitializer(w, arghGeneratedRootTypeName);
		}

		AddSource(context, "ArghGenerated.g.cs", w);
	}

	private static void EmitArghGeneratedMembers(
		CodeWriter w,
		AppEmitModel app,
		ImmutableArray<DtoBindingTarget> dtoTargets,
		string entryAssemblyName,
		string entryAssemblyVersion,
		string entrySchemaVersion)
	{
		// Static fields that hold the parsed global/namespace options instances.
		// Commands inject these via method or constructor parameters.
		var optionsTypes = new List<string>();
		if (app.GlobalOptionsModel is { } globalOptModel)
			optionsTypes.Add(globalOptModel.TypeFq);
		foreach ((var nsNode, _) in EnumerateCommandNamespaceNodesWithPath(app.Root, ImmutableArray<string>.Empty))
		{
			if (nsNode.CommandNamespaceOptionsModel is { } nsModel)
				optionsTypes.Add(nsModel.TypeFq);
		}

		foreach (var fq in optionsTypes)
			w.Line($"private static {fq} {OptionsStaticFieldNameFq(fq)} = new {fq}();");
		if (HasOptionsTypes(app))
			w.Line($"private static readonly HashSet<string> {OptionFlagsSeenField} = new HashSet<string>(StringComparer.OrdinalIgnoreCase);");
		w.Line();

		EmitCompletionForApp(w, app);
		w.Arrow("public static Task<int> RunAsync(string[] args)", "RunWithCancellationAsync(args)");
		w.Line();
		AppendRunWithCancellationAsyncMethod(w);
		EmitRunCoreHierarchical(w, app, entryAssemblyName);
		w.Line();
		EmitPrintRootHelpHierarchical(w, app, entryAssemblyName);
		w.Line();
		foreach ((var node, var path) in EnumerateCommandNamespaceNodesWithPath(app.Root, ImmutableArray<string>.Empty))
			EmitCommandNamespaceHelpPrinter(w, path, node, app, entryAssemblyName);

		foreach (var cmd in app.AllCommands)
			EmitCommandHelpPrinter(w, cmd, app, entryAssemblyName);

		foreach (var cmd in app.AllCommands)
			EmitCommandFlagHelpToStdErrMethod(w, cmd, app);

		using (w.Block("private static void PrintVersion()"))
			w.Line($"Console.Out.WriteLine({Quote(entryAssemblyVersion)});");
		w.Line();

		foreach (var cmd in app.AllCommands)
		{
			var injectedOpts = app.InjectionChains.TryGetValue(cmd.RunMethodName, out var precomputed3)
				? precomputed3
				: BuildOptionsInjectionChain(app, cmd);
			EmitCommandRunner(w, cmd, app.GlobalMiddleware, injectedOptions: injectedOpts, entryAssemblyName: entryAssemblyName, environmentPrefix: app.EnvironmentPrefix);
		}

		var globalPrefetchMembers = CollectRootPrefetchGlobalMembers(app);
		var deferRootPrefetch = CollectDeferredRootAliasPrefetchFlags(app);
		if (globalPrefetchMembers.Length > 0 || deferRootPrefetch.Length > 0)
		{
			if (app.GlobalOptionsModel is { } g)
			{
				EmitOptionsTryParse(w, "TryParseGlobalOptions",
					globalPrefetchMembers,
					storeTypeFq: g.TypeFq,
					storeFieldName: OptionsStaticFieldNameFq(g.TypeFq),
					storeBestCtorParamOrder: g.BestCtorParamOrder,
					entryAssemblyName: entryAssemblyName,
					deferLeadingRootAliasFlags: deferRootPrefetch);
			}
			else
				EmitOptionsTryParse(w, "TryParseGlobalOptions", globalPrefetchMembers,
					entryAssemblyName: entryAssemblyName,
					deferLeadingRootAliasFlags: deferRootPrefetch);
		}

		foreach ((var node, var path) in EnumerateCommandNamespaceNodesWithPath(app.Root, ImmutableArray<string>.Empty))
		{
			// Use FLATTENED members (including inherited) so flags from parent options types are
			// also recognised and consumed between the namespace segment and the sub-command.
			if (node.CommandNamespaceOptionsModel is { FlattenedMembers.Length: > 0 } nsModel)
				EmitOptionsTryParse(w, CommandNamespaceOptionsParseMethodName(path), nsModel.FlattenedMembers,
					storeTypeFq: nsModel.TypeFq,
					storeFieldName: OptionsStaticFieldNameFq(nsModel.TypeFq),
					storeBestCtorParamOrder: nsModel.BestCtorParamOrder,
					entryAssemblyName: entryAssemblyName,
					inheritedValues: InheritedOptionsValues(app, path, nsModel));
		}

		EmitTryParseRouteHierarchical(w, app);
		EmitIsIntrinsicCommand(w, app);
		EmitDispatchForNode(w, app, app.Root, ImmutableArray<string>.Empty, "DispatchRoot", isRoot: true, entryAssemblyName);
		// Static abstract interface members need a constrained generic call site, which also reaches explicit implementations.
		// IParsable<T> exists from .NET 7, and a parameter can only be IParsable when the consumer targets it.
		// Number types take ParserOptions.NumberStyles, like the built-in number types.
		const string helperParams = "(string? raw, global::Nullean.Argh.Parsing.ParserOptions options, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out T value)";
		w.PreprocessorIf("NET7_0_OR_GREATER", () =>
		{
			w.Line($"private static bool {ParsableHelperName}<T>{helperParams}");
			using (w.Indented())
				w.Line("where T : global::System.IParsable<T> => T.TryParse(raw, options.Culture, out value);");
			w.Line();
			w.Line($"private static bool {NumberBaseHelperName}<T>{helperParams}");
			using (w.Indented())
				w.Line("where T : global::System.Numerics.INumberBase<T> => T.TryParse(raw, options.NumberStyles, options.Culture, out value);");
		});
		w.Line();
		using (w.Block("private static bool? ParseNullableBool(string? raw, bool fromYesSwitch)"))
		{
			w.Line("if (string.IsNullOrEmpty(raw)) return fromYesSwitch;");
			w.Line("if (bool.TryParse(raw, out var b)) return b;");
			w.Return("fromYesSwitch");
		}

		w.Line();
		using (w.Block("private static string[] TailFrom(string[] args, int start)"))
		{
			w.Line("if (start >= args.Length) return Array.Empty<string>();");
			w.Line("var n = args.Length - start;");
			w.Line("var r = new string[n];");
			w.Line("Array.Copy(args, start, r, 0, n);");
			w.Return("r");
		}

		EmitDtoBindingMethods(w, dtoTargets);
		w.Line();
		EmitBuildCliSchemaDocumentHierarchical(w, app, entryAssemblyName, app.SchemaVersionOverride ?? entrySchemaVersion);
	}

	private static bool HasOptionsTypes(AppEmitModel app) =>
		app.GlobalOptionsModel is not null
		|| EnumerateCommandNamespaceNodesWithPath(app.Root, ImmutableArray<string>.Empty).Any(static n => n.node.CommandNamespaceOptionsModel is not null);

	/// <summary>
	/// For the options of the namespace at <paramref name="path"/>, the static each inherited member starts from: the
	/// innermost enclosing options (global or an outer namespace) that declare the same member, already parsed by then.
	/// </summary>
	private static Dictionary<string, string> InheritedOptionsValues(AppEmitModel app, ImmutableArray<string> path, OptionsTypeModel options) =>
		OptionsMemberStatics(EnclosingOptions(app, path).Select(o => (
			OptionsStaticFieldNameFq(o.TypeFq),
			o.FlattenedMembers.Where(m => options.FlattenedMembers.Any(own =>
				string.Equals(own.CliLongName, m.CliLongName, StringComparison.OrdinalIgnoreCase)
				&& own.SymbolName == m.SymbolName && own.TypeName == m.TypeName)).ToImmutableArray())));

	/// <summary>The options that enclose the namespace at <paramref name="path"/>: the global options, then each outer namespace's.</summary>
	private static IEnumerable<OptionsTypeModel> EnclosingOptions(AppEmitModel app, ImmutableArray<string> path)
	{
		if (app.GlobalOptionsModel is { } global)
			yield return global;
		var node = app.Root;
		for (var i = 0; i < path.Length - 1; i++)
		{
			var child = node.Children.FirstOrDefault(c => string.Equals(c.Segment, path[i], StringComparison.OrdinalIgnoreCase));
			if (child is null)
				yield break;
			node = child.Node;
			if (node.CommandNamespaceOptionsModel is { } outer)
				yield return outer;
		}
	}

	private static IEnumerable<(RegistryNode node, ImmutableArray<string> path)> EnumerateCommandNamespaceNodesWithPath(
		RegistryNode root,
		ImmutableArray<string> prefix)
	{
		foreach (var ch in root.Children)
		{
			var p = AppendSegment(prefix, ch.Segment);
			yield return (ch.Node, p);
			foreach ((var node, var sub) in EnumerateCommandNamespaceNodesWithPath(ch.Node, p))
				yield return (node, sub);
		}
	}

	private static string CommandNamespacePathKey(ImmutableArray<string> path)
	{
		if (path.IsDefaultOrEmpty)
			return "Root";

		var sb = new StringBuilder();
		for (var i = 0; i < path.Length; i++)
		{
			if (i > 0)
				sb.Append('_');
			sb.Append(Naming.SanitizeIdentifier(path[i]));
		}

		return sb.ToString();
	}

	private static string CommandNamespaceOptionsParseMethodName(ImmutableArray<string> path) =>
		"TryParseCommandNamespaceOptions_" + CommandNamespacePathKey(path);

	/// <summary><c>return await Run(TailFrom(args, idx[0]), ct)…;</c>: hands the rest of the arguments to a command runner.</summary>
	private static string ReturnRunTail(string runMethodName) =>
		$"return await {runMethodName}(TailFrom(args, idx[0]), ct).ConfigureAwait(false);";

	private static void EmitRunCoreHierarchical(CodeWriter w, AppEmitModel app, string entryAssemblyName)
	{
		var hasLeadingOptionPrefetch =
			CollectRootPrefetchGlobalMembers(app).Length > 0 || CollectDeferredRootAliasPrefetchFlags(app).Length > 0;
		using (w.Block("private static async Task<int> RunCoreAsync(string[] args, CancellationToken ct)"))
		{
			EmitRootCompletionScriptBlock(w, entryAssemblyName);
			EmitRootCompleteBlock(w);
			EmitRootSchemaBlock(w);
			w.Line("var idx = new int[1];");
			if (HasOptionsTypes(app))
				w.Line($"{OptionFlagsSeenField}.Clear();");
			if (hasLeadingOptionPrefetch)
				w.Line("if (!TryParseGlobalOptions(args, idx)) return 2;");

			using (w.If("idx[0] < args.Length && (args[idx[0]] == \"--help\" || args[idx[0]] == \"-h\")"))
			{
				w.Line("PrintRootHelp();");
				w.Return("0");
			}

			using (w.If("idx[0] < args.Length && args[idx[0]] == \"--version\""))
			{
				w.Line("PrintVersion();");
				w.Return("0");
			}

			using (w.If("idx[0] >= args.Length"))
			{
				if ((app.Root.RootCommand ?? app.Root.RootAlias) is { } runCoreRoot)
					w.Line(ReturnRunTail(runCoreRoot.RunMethodName));
				else
				{
					w.Line("PrintRootHelp();");
					w.Return("0");
				}
			}

			w.Return("await DispatchRoot(args, idx, ct).ConfigureAwait(false)");
		}
	}

	private static void EmitPrintRootHelpHierarchical(CodeWriter w, AppEmitModel app, string entryAssemblyName)
	{
		var rootGlobalFlags = new List<ParameterModel>();
		if ((app.Root.RootCommand is not null || app.Root.RootAlias is not null) &&
		    app.GlobalOptionsModel is OptionsTypeModel gomH && gomH.Members.Length > 0)
		{
			foreach (var p in gomH.Members)
			{
				if (p.Kind == ParameterKind.Flag)
					rootGlobalFlags.Add(p);
			}
		}

		var widthCandidatesGlobalRoot = new List<int> { "-h, --help".Length, "--version".Length };
		widthCandidatesGlobalRoot.AddRange(rootGlobalFlags.Select(p => HelpLayout.FormatOptionLeftCell(p).Length));
		var maxOptWidthRoot = Math.Min(widthCandidatesGlobalRoot.Max(), 40);
		maxOptWidthRoot = Math.Max(maxOptWidthRoot, "-h, --help".Length);

		var visibleRootChildren = app.Root.Children.Where(static ch => !ch.IsHidden)
			.OrderBy(ch => ch.Segment, StringComparer.OrdinalIgnoreCase).ThenBy(ch => ch.Segment, StringComparer.Ordinal)
			.Select(ch => (ch.Segment, ch.SummaryOneLiner))
			.ToList();
		var visibleRootCmds = app.Root.Commands.Where(static c => !c.IsHidden)
			.OrderBy(c => c.CommandName, StringComparer.OrdinalIgnoreCase).ThenBy(c => c.CommandName, StringComparer.Ordinal)
			.Select(c => (c.CommandName, c.SummaryOneLiner))
			.ToList();

		using (w.Block("private static void PrintRootHelp()"))
		{
			w.Line(HelpUsageLine(entryAssemblyName, " <namespace|command> [options]"));
			w.Line(HelpBlankLine);
			if (app.Root.RootCommand is { } rootOverview)
				EmitRootCommandHelpOverview(w, rootOverview, app, entryAssemblyName);
			else if (app.Root.RootAlias is { } rootAliasOverview)
				// Preserve the legacy MapRoot root-help shape: "(default command)" plus handler docs — not the abbreviated
				// root-alias synopsis (those details remain on the named sub-command's --help).
				EmitRootCommandHelpOverview(w, rootAliasOverview, app, entryAssemblyName, includeScopedDefaultHelpOptions: false);
			else if (!string.IsNullOrWhiteSpace(app.RootSummary))
			{
				EmitHelpDocLines(w, null, app.RootSummary, remarks: false);
				w.Line(HelpBlankLine);
			}

			w.Line(HelpSection("Global options:"));
			w.Line(HelpBuiltInRow("-h, --help", maxOptWidthRoot, "Show help."));
			w.Line(HelpBuiltInRow("--version", maxOptWidthRoot, "Show version."));
			EmitHelpOptionRows(w, rootGlobalFlags, maxOptWidthRoot);
			w.Line(HelpBlankLine);
			if (visibleRootChildren.Count > 0)
			{
				w.Line(HelpSection("Namespaces:"));
				EmitHelpListing(w, namespaces: true, visibleRootChildren);
				w.Line(HelpBlankLine);
			}

			if (visibleRootCmds.Count > 0)
			{
				w.Line(HelpSection("Commands:"));
				EmitHelpListing(w, namespaces: false, visibleRootCmds);
			}
		}
	}

	private static void EmitCommandNamespaceHelpPrinter(CodeWriter w, ImmutableArray<string> path, RegistryNode node, AppEmitModel app, string entryAssemblyName)
	{
		var key = CommandNamespacePathKey(path);
		var usagePrefix = string.Join(" ", path);

		var globalFlagMembers = EnumerateFlagMembers(app.GlobalOptionsModel).ToList();
		var namespaceOptionSections = BuildNamespaceOptionSections(app, path, globalFlagMembers);

		var hasNsDoc = !string.IsNullOrWhiteSpace(node.SummaryInnerXml);
		var showGlobalFlagsInNs = (node.RootCommand is not null || hasNsDoc) && globalFlagMembers.Count > 0;
		var showNamespaceScopedOptionSections = node.RootCommand is not null || hasNsDoc;
		var widthCandidatesNs = new List<int> { "-h, --help".Length };
		if (showGlobalFlagsInNs)
			widthCandidatesNs.AddRange(globalFlagMembers.Select(p => HelpLayout.FormatOptionLeftCell(p).Length));
		if (showNamespaceScopedOptionSections)
		{
			foreach ((_, var rows) in namespaceOptionSections)
				widthCandidatesNs.AddRange(rows.Select(p => HelpLayout.FormatOptionLeftCell(p).Length));
		}

		var maxOptWidth = Math.Min(widthCandidatesNs.Max(), 40);
		maxOptWidth = Math.Max(maxOptWidth, "-h, --help".Length);

		var visibleChildNamespaces = node.Children.Where(static ch => !ch.IsHidden)
			.OrderBy(ch => ch.Segment, StringComparer.OrdinalIgnoreCase).ThenBy(ch => ch.Segment, StringComparer.Ordinal)
			.Select(ch => (FormatQualifiedCliPath(path, ch.Segment), ch.SummaryOneLiner))
			.ToList();
		var visibleNodeCmds = node.Commands.Where(static c => !c.IsHidden)
			.OrderBy(c => c.CommandName, StringComparer.OrdinalIgnoreCase).ThenBy(c => c.CommandName, StringComparer.Ordinal)
			.Select(c => (FormatQualifiedCliPath(path, c.CommandName), c.SummaryOneLiner))
			.ToList();

		using (w.Block($"private static void PrintHelp_CommandNamespace_{key}()"))
		{
			w.Line(HelpUsageLine(entryAssemblyName, $" {usagePrefix} <command> [options]"));
			w.Line(HelpBlankLine);
			if (node.RootCommand is { } nsRootOverview)
				EmitRootCommandHelpOverview(w, nsRootOverview, app, entryAssemblyName);
			else if (node.RootAlias is { } nsAliasOverview)
				EmitRootAliasHelpOverview(w, nsAliasOverview, path, entryAssemblyName);
			else if (!string.IsNullOrWhiteSpace(node.SummaryInnerXml))
			{
				EmitHelpDocLines(w, node.SummaryInnerXml, "", remarks: false);
				w.Line(HelpBlankLine);
			}

			w.Line(HelpSection("Global options:"));
			w.Line(HelpBuiltInRow("-h, --help", maxOptWidth, "Show help."));
			if (showGlobalFlagsInNs)
				EmitHelpOptionRows(w, globalFlagMembers, maxOptWidth);

			w.Line(HelpBlankLine);

			if (showNamespaceScopedOptionSections)
			{
				foreach ((var segment, var gRows) in namespaceOptionSections)
				{
					w.Line(HelpSection($"'{segment}' options:"));
					EmitHelpOptionRows(w, gRows, maxOptWidth);
					w.Line(HelpBlankLine);
				}
			}

			if (visibleChildNamespaces.Count > 0)
			{
				w.Line(HelpSection("Namespaces:"));
				EmitHelpListing(w, namespaces: true, visibleChildNamespaces);
				w.Line(HelpBlankLine);
			}

			if (visibleNodeCmds.Count > 0)
			{
				w.Line(HelpSection("Commands:"));
				EmitHelpListing(w, namespaces: false, visibleNodeCmds);
			}

			if (node.RootCommand is null && !string.IsNullOrWhiteSpace(node.RemarksInnerXml))
			{
				w.Line(HelpBlankLine);
				EmitNotesSection(w, node.RemarksInnerXml, "");
			}
		}

		w.Line();
	}

	private static void EmitDispatchForNode(
		CodeWriter w,
		AppEmitModel app,
		RegistryNode node,
		ImmutableArray<string> path,
		string methodName,
		bool isRoot,
		string entryAssemblyName)
	{
		var printHelp = isRoot ? "PrintRootHelp();" : $"PrintHelp_CommandNamespace_{CommandNamespacePathKey(path)}();";
		using (w.Block($"private static async Task<int> {methodName}(string[] args, int[] idx, CancellationToken ct)"))
		{
			// Call namespace options parse for any namespace that has a registered options type (even if it only
			// inherits flags from a parent type) so that flags between the namespace segment and the sub-command
			// are consumed correctly.
			if (!isRoot && node.CommandNamespaceOptionsModel is { FlattenedMembers.Length: > 0 })
				w.Line($"if (!{CommandNamespaceOptionsParseMethodName(path)}(args, idx)) return 2;");

			using (w.If("idx[0] >= args.Length"))
			{
				if ((node.RootCommand ?? node.RootAlias) is { } dispatchRoot)
					w.Line(ReturnRunTail(dispatchRoot.RunMethodName));
				else
				{
					w.Line(printHelp);
					w.Return("0");
				}
			}

			using (w.If("args[idx[0]] == \"--help\" || args[idx[0]] == \"-h\""))
			{
				w.Line(printHelp);
				w.Return("0");
			}

			w.Line("var tok = args[idx[0]];");
			foreach (var cmd in node.Commands)
			{
				using (w.If($"string.Equals(tok, {Quote(cmd.CommandName)}, StringComparison.OrdinalIgnoreCase)"))
				{
					w.Line("idx[0]++;");
					w.Line(ReturnRunTail(cmd.RunMethodName));
				}
			}

			foreach (var ch in node.Children)
			{
				var childMethod = "DispatchCommandNamespace_" + CommandNamespacePathKey(AppendSegment(path, ch.Segment));
				using (w.If($"string.Equals(tok, {Quote(ch.Segment)}, StringComparison.OrdinalIgnoreCase)"))
				{
					w.Line("idx[0]++;");
					w.Return($"await {childMethod}(args, idx, ct).ConfigureAwait(false)");
				}
			}

			if ((node.RootCommand ?? node.RootAlias) is { } flagFallback)
			{
				using (w.If("tok.Length > 0 && tok[0] == '-'"))
					w.Line(ReturnRunTail(flagFallback.RunMethodName));
			}

			using (w.Block())
				EmitFuzzyDispatchDefault(w, node, path, entryAssemblyName);
		}

		w.Line();
		foreach (var ch in node.Children)
		{
			var childPath = AppendSegment(path, ch.Segment);
			EmitDispatchForNode(w, app, ch.Node, childPath, "DispatchCommandNamespace_" + CommandNamespacePathKey(childPath), isRoot: false, entryAssemblyName);
		}
	}
